CREATE TABLE IF NOT EXISTS {PREFIX}lacrm_events (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    lacrm_event_id VARCHAR(50) NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT NULL,
    location VARCHAR(255) NULL,
    start_date DATETIME NOT NULL,
    end_date DATETIME NOT NULL,
    is_all_day TINYINT(1) NOT NULL DEFAULT 0,
    is_recurring TINYINT(1) NOT NULL DEFAULT 0,
    recurrence_rule VARCHAR(500) NULL,
    recurrence_parent_id VARCHAR(50) NULL,
    series_number INT UNSIGNED NULL,
    lacrm_user_ids JSON NULL,
    lacrm_contact_ids JSON NULL,
    attendees JSON NULL,
    raw_payload JSON NULL,
    synced_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_lacrm_events_lacrm_event_id (lacrm_event_id),
    KEY idx_lacrm_events_start_date (start_date),
    KEY idx_lacrm_events_deleted_at (deleted_at),
    KEY idx_lacrm_events_recurrence_parent (recurrence_parent_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
